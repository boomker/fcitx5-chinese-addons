"""Generate polyphonic-character reading usage from Unicode 17.0.0 Unihan."""

import argparse
import hashlib
from pathlib import Path
import re
import unicodedata
import zipfile

SOURCE_SHA256 = "f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Unicode 17.0.0 ucd/Unihan.zip")
    parser.add_argument("pinyin_table", type=Path, help="packaged pinyinhelper/py_table.mb")
    parser.add_argument("output", type=Path, help="generated pinyinreadingdata.h")
    args = parser.parse_args()
    if hashlib.sha256(args.source.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error("Unihan.zip does not match the pinned Unicode 17.0.0 SHA-256")

    polyphonic = set()
    data = args.pinyin_table.read_bytes()
    offset = 0
    while offset < len(data):
        size = data[offset]
        offset += 1
        character = data[offset:offset + size].decode("utf-8")
        offset += size
        count = data[offset]
        offset += 1 + count * 3
        if count > 1:
            polyphonic.add(ord(character))
    assert offset == len(data)

    entries = {}
    with zipfile.ZipFile(args.source) as archive:
        lines = archive.read("Unihan_Readings.txt").decode("utf-8").splitlines()
    for line in lines:
        if not line.startswith("U+"):
            continue
        character, field, value = line.split("\t", 2)
        codepoint = int(character[2:], 16)
        if codepoint not in polyphonic:
            continue
        if field == "kHanyuPinlu":
            for reading, frequency in re.findall(r"([^\s()]+)\((\d+)\)", value):
                reading = unicodedata.normalize("NFC", reading.lower())
                entries.setdefault((codepoint, reading), [0, False])[0] = int(frequency)
        elif field == "kMandarin":
            # A second value is the Taiwan preference, not a second frequency.
            reading = unicodedata.normalize("NFC", value.split()[0].lower())
            entries.setdefault((codepoint, reading), [0, False])[1] = True

    output = [
        "/*",
        " * Generated by tools/generate-pinyin-reading-data.py; do not edit.",
        " * Source: https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip",
        " * kHanyuPinlu supplies observed reading frequencies; kMandarin supplies",
        " * the customary mainland reading when frequencies are unavailable.",
        " * SPDX-FileCopyrightText: 1991-2025 Unicode, Inc.",
        " * SPDX-License-Identifier: Unicode-3.0",
        " * See LICENSES/Unicode-3.0.txt for the copyright and permission notice.",
        " */",
        "#ifndef _PINYIN_PINYINREADINGDATA_H_",
        "#define _PINYIN_PINYINREADINGDATA_H_",
        "#include <cstdint>",
        "#include <string_view>",
        "namespace fcitx {",
        "struct PinyinReadingUsage {",
        "    uint32_t character;",
        "    std::string_view reading;",
        "    int frequency;",
        "    bool customary;",
        "};",
        "inline constexpr PinyinReadingUsage PinyinReadingData[] = {",
    ]
    for (codepoint, reading), (frequency, customary) in sorted(entries.items()):
        output.append(f'    {{0x{codepoint:X}, "{reading}", {frequency}, {str(customary).lower()}}},')
    output.extend(["};", "} // namespace fcitx", "#endif", ""])
    args.output.write_text("\n".join(output), encoding="utf-8")
    print(f"Wrote {len(entries)} reading usage entries for {len(polyphonic)} polyphonic characters")


if __name__ == "__main__":
    main()
